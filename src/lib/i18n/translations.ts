export const TRANSLATIONS: Record<Language, Record<string, string>> = {
  en: EN,
  es: ES,
};

/** Look up a UI string. Falls back to English, then `fallback`, then the key itself. */
export function t(lang: Language, key: string, fallback?: string): string {
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? fallback ?? key;
}

/** Like `t`, but replaces {placeholders} with the given values. */
export function tf(
  lang: Language,
  key: string,
  vars: Record<string, string | number>,
  fallback?: string,
): string {
  return t(lang, key, fallback).replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
